fails = []


def check(cond, msg):
    if not cond:
        fails.append(msg)


def note(no, title, cats, blocks, text=""):
    return {"no": no, "title": title, "categories": cats, "text": text, "blocks": blocks,
            "tables": [b["table"] for b in blocks if "table" in b]}


